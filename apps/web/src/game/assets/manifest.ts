import type { Species } from '@ludo3d/shared';
import { DEFAULT_CLIP_NAMES, type AnimState } from '../characters/animStates';

/**
 * Asset manifest — the single source of truth for every 3D asset the game
 * loads. Swapping a proxy for a final production model is a data change here
 * (path, transforms, clip names, status), never a code change elsewhere.
 * Human-readable mirror: docs/ASSET_MANIFEST.md.
 */
export type AssetStatus =
  /** Generated in code by this repository; NOT a realistic final character. */
  | 'proxy'
  /** Final production asset supplied by an artist/vendor. */
  | 'final';

export interface AnimalAssetEntry {
  id: string;
  species: Species;
  /** Public URL of the GLB. */
  path: string;
  status: AssetStatus;
  source: string;
  licence: string;
  /** Uniform scale applied after loading so the animal fits one board square. */
  scale: number;
  /** Euler XYZ (radians) correcting the model's forward axis to +Z. */
  rotation: [number, number, number];
  /** Offset so the feet rest exactly on y = 0. */
  position: [number, number, number];
  /** Clip names inside the GLB for each required animation state. */
  clips: Record<AnimState, string>;
  /** Encounter-specific variants (attack/reaction choreography), name → clip. */
  extraClips: readonly string[];
  materials: string;
}

